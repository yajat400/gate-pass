create or replace function public.visitor_request(
  p_name text, p_phone text, p_host_name text, p_purpose text,
  p_duration_minutes integer, p_access_code text
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_pass public.visitor_passes%rowtype; v_token uuid;
begin
  if length(btrim(coalesce(p_name, ''))) not between 2 and 100 then
    return jsonb_build_object('ok', false, 'error', 'Enter a visitor name between 2 and 100 characters.');
  end if;
  if length(btrim(coalesce(p_phone, ''))) not between 7 and 30 then
    return jsonb_build_object('ok', false, 'error', 'Enter a valid contact number.');
  end if;
  if length(btrim(coalesce(p_host_name, ''))) not between 2 and 100 then
    return jsonb_build_object('ok', false, 'error', 'Enter the name of the person being visited.');
  end if;
  if length(btrim(coalesce(p_purpose, ''))) not between 3 and 300 then
    return jsonb_build_object('ok', false, 'error', 'Enter a short reason for the visit.');
  end if;
  if p_duration_minutes is null or p_duration_minutes not between 15 and 480 then
    return jsonb_build_object('ok', false, 'error', 'Choose a visit duration from 15 minutes to 8 hours.');
  end if;
  if length(coalesce(p_access_code, '')) not between 6 and 64 then
    return jsonb_build_object('ok', false, 'error', 'Choose an access code between 6 and 64 characters.');
  end if;

  insert into public.visitor_passes
    (visitor_name, phone, host_name, purpose, requested_minutes, access_code_hash, qr_token)
  values
    (btrim(p_name), btrim(p_phone), btrim(p_host_name), btrim(p_purpose), p_duration_minutes,
     extensions.crypt(p_access_code, extensions.gen_salt('bf')), gen_random_uuid()::text)
  returning * into v_pass;

  v_token := gen_random_uuid();
  insert into public.app_sessions (token_hash, role, visitor_pass_id, expires_at)
  values (encode(extensions.digest(v_token::text, 'sha256'), 'hex'), 'visitor', v_pass.id, now() + interval '24 hours');

  return jsonb_build_object('ok', true, 'visitorId', v_pass.id, 'sessionToken', v_token, 'status', v_pass.status);
end;
$$;

