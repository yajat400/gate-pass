create or replace function public.admin_pending_visitors(p_session_token uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_admin_id bigint; v_requests jsonb;
begin
  select se.admin_id into v_admin_id from public.app_sessions se
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex')
    and se.role = 'admin' and se.expires_at > now();
  if not found then return jsonb_build_object('ok', false, 'error', 'Admin session expired. Sign in again.'); end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', q.id, 'name', q.visitor_name, 'phone', q.phone, 'host', q.host_name,
    'purpose', q.purpose, 'requestedMinutes', q.requested_minutes, 'requestedAt', q.requested_at
  ) order by q.requested_at), '[]'::jsonb)
  into v_requests from (
    select * from public.visitor_passes where status = 'PENDING' order by requested_at limit 100
  ) q;
  return jsonb_build_object('ok', true, 'requests', v_requests);
end;
$$;

create or replace function public.admin_decide_visitor(p_session_token uuid, p_visitor_id bigint, p_decision text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_admin_id bigint; v_pass public.visitor_passes%rowtype; v_decision text;
begin
  select se.admin_id into v_admin_id from public.app_sessions se
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex')
    and se.role = 'admin' and se.expires_at > now();
  if not found then return jsonb_build_object('ok', false, 'error', 'Admin session expired. Sign in again.'); end if;
  v_decision := upper(btrim(coalesce(p_decision, '')));
  if v_decision not in ('APPROVE', 'REJECT') then return jsonb_build_object('ok', false, 'error', 'Choose approve or reject.'); end if;
  select * into v_pass from public.visitor_passes where id = p_visitor_id for update;
  if not found or v_pass.status <> 'PENDING' then
    return jsonb_build_object('ok', false, 'error', 'This request is no longer pending.');
  end if;
  if v_decision = 'APPROVE' then
    update public.visitor_passes
    set status = 'APPROVED', approved_at = now(), expires_at = now() + make_interval(mins => requested_minutes)
    where id = v_pass.id returning * into v_pass;
  else
    update public.visitor_passes set status = 'REJECTED' where id = v_pass.id returning * into v_pass;
  end if;
  return jsonb_build_object('ok', true, 'id', v_pass.id, 'status', v_pass.status, 'expiresAt', v_pass.expires_at);
end;
$$;

create or replace function public.guard_visitor_list(p_session_token uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_guard_id bigint; v_visitors jsonb;
begin
  select se.guard_id into v_guard_id from public.app_sessions se
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex')
    and se.role = 'guard' and se.expires_at > now();
  if not found then return jsonb_build_object('ok', false, 'error', 'Guard session expired. Sign in again.'); end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', q.id, 'name', q.visitor_name, 'phone', q.phone, 'host', q.host_name, 'purpose', q.purpose,
    'gateStatus', q.gate_status,
    'passStatus', case when q.expires_at <= now() then 'OVERDUE' else 'ACTIVE' end,
    'expiresAt', q.expires_at
  ) order by q.expires_at), '[]'::jsonb)
  into v_visitors
  from public.visitor_passes q
  where q.status = 'APPROVED'
    and (q.expires_at > now() or (q.gate_status = 'IN' and q.expires_at <= now()));
  return jsonb_build_object('ok', true, 'visitors', v_visitors);
end;
$$;

create or replace function public.guard_lookup_visitor(p_session_token uuid, p_qr_token text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_guard_id bigint; v_pass public.visitor_passes%rowtype;
begin
  select se.guard_id into v_guard_id from public.app_sessions se
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex')
    and se.role = 'guard' and se.expires_at > now();
  if not found then return jsonb_build_object('ok', false, 'error', 'Guard session expired. Sign in again.'); end if;
  select * into v_pass from public.visitor_passes
  where qr_token = btrim(p_qr_token) and status = 'APPROVED';
  if not found then return jsonb_build_object('ok', false, 'error', 'Approved visitor pass not found.'); end if;
  return jsonb_build_object('ok', true, 'visitor', jsonb_build_object(
    'id', v_pass.id, 'name', v_pass.visitor_name, 'phone', v_pass.phone, 'host', v_pass.host_name,
    'purpose', v_pass.purpose, 'gateStatus', v_pass.gate_status, 'expiresAt', v_pass.expires_at,
    'passStatus', case when v_pass.expires_at <= now() then 'OVERDUE' else 'ACTIVE' end,
    'qrToken', v_pass.qr_token
  ));
end;
$$;

create or replace function public.guard_record_visitor_scan(
  p_session_token uuid, p_qr_token text, p_movement text, p_id_checked boolean
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_guard_id bigint; v_pass public.visitor_passes%rowtype; v_movement text;
begin
  select se.guard_id into v_guard_id from public.app_sessions se
  where se.token_hash = encode(extensions.digest(p_session_token::text, 'sha256'), 'hex')
    and se.role = 'guard' and se.expires_at > now();
  if not found then return jsonb_build_object('ok', false, 'error', 'Guard session expired. Sign in again.'); end if;
  if p_id_checked is distinct from true then return jsonb_build_object('ok', false, 'error', 'Confirm that you checked the visitor ID.'); end if;
  v_movement := upper(btrim(coalesce(p_movement, '')));
  if v_movement not in ('ENTRY', 'EXIT') then return jsonb_build_object('ok', false, 'error', 'Select Entry or Exit.'); end if;
  select * into v_pass from public.visitor_passes
  where qr_token = btrim(p_qr_token) and status = 'APPROVED' for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'Approved visitor pass not found.'); end if;
  if v_movement = 'ENTRY' then
    if v_pass.expires_at <= now() then return jsonb_build_object('ok', false, 'error', 'This visitor pass has expired.'); end if;
    if v_pass.gate_status <> 'OUT' then return jsonb_build_object('ok', false, 'error', 'Visitor is already marked IN.'); end if;
    update public.visitor_passes set gate_status = 'IN' where id = v_pass.id returning * into v_pass;
  else
    if v_pass.gate_status <> 'IN' then return jsonb_build_object('ok', false, 'error', 'Record Entry before Exit.'); end if;
    update public.visitor_passes
    set gate_status = 'OUT', status = 'COMPLETED', resolved_at = now()
    where id = v_pass.id returning * into v_pass;
  end if;
  insert into public.visitor_gate_events (visitor_pass_id, guard_id, movement)
  values (v_pass.id, v_guard_id, v_movement);
  return jsonb_build_object('ok', true, 'movement', v_movement, 'visitor', jsonb_build_object(
    'name', v_pass.visitor_name, 'gateStatus', v_pass.gate_status, 'status', v_pass.status
  ));
end;
$$;

